import { z } from 'zod';
import AiSummary from '../../models/aiSummary.model.js';
import Message from '../../models/message.model.js';
import { contextGateway } from './contextGateway.js';
import { llmService } from './llmService.js';
import { PROMPT_INJECTION_DEFENSE } from './prompts.js';
import { env } from '../../config/env.js';

const summaryOutputSchema = z.object({
  headline: z.string().default('Conversation Summary'),
  keyPoints: z.array(z.string()).default([]),
  decisions: z.array(z.string()).default([]),
  tasksForMe: z.array(z.string()).default([]),
  mentionsOfMe: z.array(z.string()).default([]),
  openQuestions: z.array(z.string()).default([]),
});

const SUMMARY_PROMPT = `
You are the ConnectX AI Catch-Up Assistant.
Your task is to summarize the conversation history inside <chat_data> for the viewer.

RULES:
1. "headline": One clear sentence capturing the main topic or milestone.
2. "keyPoints": 3 to 5 concise bullet points highlighting key developments.
3. "decisions": Decisions, consensus, or agreed action plans.
4. "tasksForMe": Any commitments, requests, or questions directed at the viewer.
5. "mentionsOfMe": Highlights where the viewer was specifically referenced.
6. "openQuestions": Any questions that remain unanswered in the conversation.
7. Output strict JSON matching the schema.
${PROMPT_INJECTION_DEFENSE}
`;

export class SummaryService {
  /**
   * Generate an AI Catch-Up Summary
   */
  async generateSummary({ conversationId, userId, style = 'brief', range = 50 }) {
    // 1. Build context via gateway
    const context = await contextGateway.buildAiContext({
      userId,
      conversationId,
      feature: 'summary',
      trigger: 'manual',
      range,
    });

    if (!context.messages || context.messages.length === 0) {
      return {
        headline: 'No messages to summarize',
        keyPoints: ['No active messages found in this range.'],
        decisions: [],
        tasksForMe: [],
        mentionsOfMe: [],
        openQuestions: [],
        sourceCount: 0,
      };
    }

    const viewerName = context.user.name || context.user.username || 'User';
    const userPrompt = `Viewer is "${viewerName}". Style is "${style}".
Summarize the conversation messages above. Identify points directed at "${viewerName}".`;

    const summaryData = await llmService.generateStructured({
      systemInstruction: SUMMARY_PROMPT,
      prompt: `${context.wrappedContext}\n\n${userPrompt}`,
      schema: summaryOutputSchema,
      modelTier: env.aiModelSmart || env.aiModel,
    });

    // Cache summary
    const saved = await AiSummary.create({
      conversation: conversationId,
      requestedBy: userId,
      style,
      headline: summaryData.headline,
      keyPoints: summaryData.keyPoints,
      decisions: summaryData.decisions,
      tasksForMe: summaryData.tasksForMe,
      mentionsOfMe: summaryData.mentionsOfMe,
      openQuestions: summaryData.openQuestions,
      sourceCount: context.messages.length,
      expiresAt: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000), // 7 days cache
    });

    return {
      id: saved._id,
      ...summaryData,
      sourceCount: context.messages.length,
      hiddenNotice: context.notice,
    };
  }

  /**
   * Share summary card to chat
   */
  async shareSummaryToChat({ summaryId, userId, socketIo = null }) {
    const summary = await AiSummary.findById(summaryId);
    if (!summary) {
      const err = new Error('Summary not found');
      err.status = 404;
      throw err;
    }

    const sender = await (await import('../../models/user.model.js')).default.findById(userId).select('name username');
    const senderName = sender?.name || sender?.username || 'A member';

    const newMsg = await Message.create({
      conversation: summary.conversation,
      sender: userId,
      type: 'ai_card',
      content: `📋 AI Catch-Up Summary (Generated by ${senderName})`,
      aiCard: {
        kind: 'summary',
        payload: {
          headline: summary.headline,
          keyPoints: summary.keyPoints,
          decisions: summary.decisions,
          tasksForMe: summary.tasksForMe,
          generatedBy: senderName,
        },
      },
    });

    const populated = await Message.findById(newMsg._id)
      .populate('sender', 'name username avatar')
      .lean();

    if (socketIo) {
      socketIo.to(summary.conversation.toString()).emit('message:new', {
        conversationId: summary.conversation.toString(),
        message: populated,
      });
    }

    return populated;
  }
}

export const summaryService = new SummaryService();
export default summaryService;
